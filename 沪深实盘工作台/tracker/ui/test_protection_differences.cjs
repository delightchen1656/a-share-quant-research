const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync(__dirname+'/index.html','utf8');
const code=html.slice(html.indexOf('function protectionDifference('),html.indexOf('function render(){'));
const c={};vm.createContext(c);vm.runInContext(code,c);
assert.equal(c.protectionDifference({average_price:10,take:11.2},'take'),'+1.20元（+12.00%）');
assert.equal(c.protectionDifference({average_price:10,stop:9.55},'stop'),'-0.45元（-4.50%）');
assert.equal(c.protectionDifference({average_price:9.5,stop:9.64},'stop'),'+0.14元（+1.47%）');
assert.equal(c.protectionDifference({average_price:2.923,stop:2.8},'stop'),'-0.123元（-4.21%）');
assert.equal(c.protectionTargetText({average_price:10,take:11.2},'take'),'11.20 (+1.20元)(+12.00%)');
assert.equal(c.protectionTargetText({average_price:10,stop:9.55},'stop'),'9.55 (-0.45元)(-4.50%)');
const protect=html.slice(html.indexOf('function protect(')).split('\n')[0];
assert.ok(!protect.includes("card('委托类型'"));
assert.ok(!protect.includes("card('止盈差额"));
assert.ok(protect.includes("card('止盈 ≥',protectionTargetText(p,'take'),p.take.toFixed(2))"));
assert.ok(protect.includes("card('止损 ≤',protectionTargetText(p,'stop'),p.stop.toFixed(2))"));
const scripts=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
for(const script of scripts)new vm.Script(script);
assert.ok(html.includes('模型原买入线（仅供对照）'));
assert.ok(html.includes('实际成交均价（止盈止损计算基准）'));
console.log('PASS model target / actual fill differences, positive stop difference, fractional-cent average, inline JS syntax');
